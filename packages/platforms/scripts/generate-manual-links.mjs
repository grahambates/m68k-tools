#!/usr/bin/env node
// Regenerates src/amiga/manual-links.ts: the page of the Amiga Hardware
// Reference Manual (Appendix A, register summary) that documents each custom
// chip register, from the manual's alphabetical index.
//
//   node scripts/generate-manual-links.mjs [index.html]
//
// With no argument the index is fetched from the Amiga Developer CD 2.1 copy
// at amigadev.elowar.com. Its HTTPS certificate has expired, so plain HTTP is
// used, which is also what the links themselves use.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const base = "http://amigadev.elowar.com/read/ADCD_2.1/Hardware_Manual_guide/";
const indexPage = "node0011.html";

const html = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch(base + indexPage)).text();

// Grouped entries name a family with a placeholder: AUDxDAT, SPRxPOS, COLORxx.
const families = [
  [/^AUDx/, ["0", "1", "2", "3"], "AUD"],
  [/^BLTx/, ["A", "B", "C", "D"], "BLT"],
  [/^BPLx/, ["1", "2", "3", "4", "5", "6"], "BPL"],
  [/^SPRx/, ["0", "1", "2", "3", "4", "5", "6", "7"], "SPR"],
];

const explicit = new Map();
const grouped = new Map();
for (const [, page, name] of html.matchAll(
  /<a href="\.\.\/Hardware_Manual_guide\/(node[0-9A-F]+\.html(?:#line\d+)?)">([A-Z0-9x]+)<\/a>/g,
)) {
  if (name === "COLORxx") {
    for (let i = 0; i < 32; i++)
      grouped.set(`COLOR${String(i).padStart(2, "0")}`, page);
    continue;
  }
  const family = families.find(([pattern]) => pattern.test(name));
  if (!family) {
    explicit.set(name, page);
    continue;
  }
  const [pattern, members, prefix] = family;
  for (const member of members)
    grouped.set(name.replace(pattern, prefix + member), page);
}

// A register the index names itself keeps its own page: BLTDDAT is listed apart
// from BLTxDAT.
const links = new Map([...grouped, ...explicit]);
const entries = [...links].sort(([a], [b]) => a.localeCompare(b));
if (entries.length < 150)
  throw new Error(
    `Only ${entries.length} registers found; has the index changed?`,
  );

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/amiga/manual-links.ts",
);
writeFileSync(
  out,
  [
    "// Generated by scripts/generate-manual-links.mjs. Do not edit by hand.",
    "",
    "/** The Amiga Developer CD 2.1 copy of the Amiga Hardware Reference Manual. */",
    `export const HARDWARE_MANUAL_BASE =\n  ${JSON.stringify(base)};`,
    "",
    "/** Each register's page in the manual's register summary, by name. */",
    "export const hardwareManualPages: ReadonlyMap<string, string> = new Map([",
    ...entries.map(
      ([name, page]) => `  [${JSON.stringify(name)}, ${JSON.stringify(page)}],`,
    ),
    "]);",
    "",
  ].join("\n"),
);
console.log(`Wrote ${out} (${entries.length} registers)`);
